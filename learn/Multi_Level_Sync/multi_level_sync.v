module multi_level_sync(
    input clk,
    input in,
    input rst_n,
    output out
);
    reg q1,q2,q3;

    always@(posedge clk or negedge rst_n) begin
        if(rst_n ==0) begin
            q1 <= 0;
            q2 <= 0;
            q3 <= 0; 
        end
        else 
            q1<=in;  //第一级同步 抵抗亚稳态
            q2<=q1;  //第二级同步保持稳定
            q3<=q2;  //第三级 保持上一个信号稳定
    end

    assign out = q2^q3;  // 双边沿检测

    // assign rise_p  = q2 & (~q3);        //上升沿
    // assign fall_p  = (~q2) & q3;        //下降沿
    // assign both_p  = q2 ^ q3;           //双边沿，异或！！！



endmodule




/*
一、什么时候要用多级寄存器（同步打拍）
核心本质：处理跨时钟域（异步信号），抑制亚稳态！
1）场景 1：外部慢速 IO 输入（按键、拨码、传感器，就是你刚才这道题）
板子外部引脚进来的信号in和本模块时钟clk是异步的！外部信号随时可以跳变，不一定对齐 clk 上升沿。
直接拿这个原始信号做逻辑判断，有可能碰到建立 / 保持时间违例，产生亚稳态（寄存器输出出现一段不定态 X），后续逻辑直接出错。
👉做法：先打 2 拍同步，再做边沿检测。（就是刚才的上升沿检测题目）
2）场景 2：真正跨时钟域 CDC（clock domain crossing）
信号从 A 时钟域 → B 时钟域；
如果是单 bit 信号（电平、脉冲）：两级同步寄存器（2‑flop synchronizer）
如果是多 bit 数据总线：不能直接打拍！！必须用 FIFO / 握手 / 格雷码！！这点非常重要！很多人踩坑！
3）场景 3：单纯延迟（时序对齐，流水线）
同一个时钟域内部，连续几级寄存器打拍，只是单纯延时信号，用来对齐多条路径时序，不属于同步，属于流水线延时。
⚠同一个时钟域内部，不需要为防亚稳态打拍！！只有异步输入才需要！
❗误区（做题经常踩）
同一个时钟域内部信号，再额外多加两级同步寄存器属于多余；
多 bit 总线千万不要直接多级打拍同步！会发生数据撕裂！！
二、通用范式（分 3 种常用模板，可以直接背下来）
📌范式 1：单 bit 异步输入，两级同步（2‑flop 同步器，最常用！）
适用：外部按键、传感器、从别的异步时钟过来的 1bit 电平信号；之后再做边沿检测
verilog
reg q1, q2;
always @(posedge clk) begin
    q1 <= async_in;   //第一级：接收异步信号，抵抗亚稳态
    q2 <= q1;         //第二级：输出稳定的同步之后的信号，后续逻辑拿q2使用！
end
//后续逻辑全部使用q2，不要再直接使用原始async_in！！
💡做题仿真的时候，如果要消除初始 X 态（就像刚才那道习题）加 initial；真实 FPGA 工程不要写 initial，依靠复位！！工程优先用复位！！
工程版（推荐！使用复位代替 initial！！）
verilog
reg q1, q2;
always @(posedge clk or negedge rst_n) begin
    if(!rst_n) begin
        q1 <= 1'b0;
        q2 <= 1'b0;
    end
    else begin
        q1 <= async_in;
        q2 <= q1;
    end
end
📌范式 2：在两级同步之后做边沿检测（就是你这道原题完整范式）
先同步，再检测边沿！顺序千万不能颠倒！不要拿原始异步信号直接做边沿判断！！这是考点！！
verilog
//第一步：异步输入先两级同步
reg q1,q2;
always @(posedge clk) begin
    q1 <= in;
    q2 <= q1;
end
//第二步：对同步后的q2再打一拍得到q3，用来保存上一拍的值做边沿识别
reg q3;
always @(posedge clk) begin
    q3 <= q2;
end
assign rise_pulse = q2 & (~q3);      //上升沿检测，输出单周期脉冲
assign fall_pulse = (~q2) & q3;      //下降沿检测
assign edge_pulse = q2 ^ q3;         //双边沿检测
📝时序记忆口诀：
异步信号先同步；同步之后再打一拍；再做边沿判断！
刚才那道练习题的写法 q1<=in; q2<=q1; out = q1 & ~q2；这里 q1 是同步输出，q2 保存上一拍；等价这套范式。
📌范式 3：三级同步（什么时候用？高速时钟，时钟频率很高，亚稳态恢复时间紧张）
极少数高速设计，担心两级还来不及消除亚稳态，使用 3 级寄存器；
verilog
reg q1,q2,q3;
always @(posedge clk) begin
    q1 <= async_in;
    q2 <= q1;
    q3 <= q2;
end
//后续逻辑使用q3
绝大多数普通 FPGA 设计两级同步足够，三级用的不多。
🧠记忆总结（笔记版，可以直接记）
什么时候多级同步寄存器？只要是【单 bit 异步输入】！外部 IO、别的时钟域过来的 1bit 信号。目的：降低亚稳态概率；
❗多 bit 信号禁止直接打拍同步！FIFO / 握手 / 格雷码；
边沿检测的标准流程口诀：异步先同步，同步后再寄存，然后判断前后两拍电平！！不要拿原始异步信号直接检测边沿！（这就是你第一次写代码出错的根本原因）
